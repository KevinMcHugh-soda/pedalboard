#!/usr/bin/env bash
#
# build.sh — compile with SwiftPM, assemble a macOS .app bundle, codesign.
#
# Usage:  ./build.sh [debug|release]
#
# Driven by the Makefile. NO Xcode IDE, NO xcodebuild — `swift build` does
# the compile, this script does the bundling and signing. Xcode is only a
# toolchain provider (swift / codesign).
#
# Environment:
#   SIGN_IDENTITY      codesign identity. Defaults to ad-hoc ("-"), which is
#                      all you need for `make run` on your own machine.
#   PROVISION_PROFILE  optional .provisionprofile to embed (release/dist).
#   VERSION            CFBundleShortVersionString to stamp (default 0.0.0).
#   VARIANT            dev (default) or installed. A dev build is "Pedalboard Dev.app"
#                      with its own bundle id and defaults domain, so it
#                      never touches the installed copy. Only scripts/promote.sh
#                      (make install) builds the installed variant.
#   COMMIT             commit to stamp as PedalboardCommit (default: HEAD, +dirty).
#
set -euo pipefail

CONFIG="${1:-debug}"
VARIANT="${VARIANT:-dev}"
EXE_NAME="PedalboardApp"   # bundle is Pedalboard.app; binary inside is PedalboardApp
CLI_NAME="pedal"
BUILD_DIR="build"
SIGN_IDENTITY="${SIGN_IDENTITY:--}"
PROVISION_PROFILE="${PROVISION_PROFILE:-}"
VERSION="${VERSION:-0.0.0}"
ENTITLEMENTS="Pedalboard/Pedalboard.entitlements"
INFO_PLIST_SRC="Resources/Info.plist"

# Must agree with AppVariant in Sources/PedalboardCore/AppVariant.swift.
case "$VARIANT" in
	dev)
		APP_NAME="Pedalboard Dev"
		BUNDLE_ID="dev.pedalboard.app.dev"
		ICON="$BUILD_DIR/AppIconDev.icns"
		SWIFT_FLAGS=()
		;;
	installed)
		APP_NAME="Pedalboard"
		BUNDLE_ID="dev.pedalboard.app"
		ICON="$BUILD_DIR/AppIcon.icns"
		SWIFT_FLAGS=(-Xswiftc -DPEDALBOARD_INSTALLED)
		;;
	*)
		echo "✗ VARIANT must be dev or installed, not '$VARIANT'" >&2
		exit 1
		;;
esac
APP="$BUILD_DIR/$APP_NAME.app"

if [ -z "${COMMIT:-}" ]; then
	COMMIT="$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
	if [ -n "$(git status --porcelain --untracked-files=no 2>/dev/null)" ]; then
		COMMIT="$COMMIT+dirty"
	fi
fi

# Build number: monotonic-ish from the date so re-signs differ. Falls back to 1.
BUILD_NUMBER="$(date +%Y%m%d%H%M 2>/dev/null || echo 1)"

echo "→ swift build -c $CONFIG ($VARIANT)"
swift build -c "$CONFIG" ${SWIFT_FLAGS[@]+"${SWIFT_FLAGS[@]}"}

BIN_PATH="$(swift build -c "$CONFIG" --show-bin-path)"
EXECUTABLE="$BIN_PATH/$EXE_NAME"
if [ ! -x "$EXECUTABLE" ]; then
	echo "✗ executable not found at $EXECUTABLE" >&2
	exit 1
fi

# ---------------------------------------------------------------------------
# Assemble the bundle
# ---------------------------------------------------------------------------
echo "→ assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cp "$EXECUTABLE" "$APP/Contents/MacOS/$EXE_NAME"

# Ship the CLI inside the bundle, next to the app it controls.
if [ -x "$BIN_PATH/$CLI_NAME" ]; then
	cp "$BIN_PATH/$CLI_NAME" "$APP/Contents/MacOS/$CLI_NAME"
fi

# Info.plist — substitute version placeholders.
sed -e "s/__SHORT_VERSION__/$VERSION/g" \
    -e "s/__BUILD_VERSION__/$BUILD_NUMBER/g" \
    -e "s/__BUNDLE_ID__/$BUNDLE_ID/g" \
    -e "s/__APP_NAME__/$APP_NAME/g" \
    -e "s/__COMMIT__/$COMMIT/g" \
    "$INFO_PLIST_SRC" > "$APP/Contents/Info.plist"

# PkgInfo — classic 8-byte file some macOS code paths still look for.
printf 'APPL????' > "$APP/Contents/PkgInfo"

# SwiftPM resource bundles — if any dependency ships a `*.bundle`, copy it
# into Contents/Resources so the app finds it once moved away from `.build`.
for bundle in "$BIN_PATH"/*.bundle; do
	if [ -e "$bundle" ]; then
		cp -R "$bundle" "$APP/Contents/Resources/"
		echo "  bundled $(basename "$bundle")"
	fi
done

# App icon (optional — generated by `make icon`). Info.plist names AppIcon
# either way; the dev variant's carries a DEV band.
if [ -f "$ICON" ]; then
	cp "$ICON" "$APP/Contents/Resources/AppIcon.icns"
else
	echo "  (no $ICON — run 'make icon'; bundling without one)"
fi

# Embed a provisioning profile if one was supplied.
if [ -n "$PROVISION_PROFILE" ] && [ -f "$PROVISION_PROFILE" ]; then
	cp "$PROVISION_PROFILE" "$APP/Contents/embedded.provisionprofile"
	echo "  embedded provisioning profile"
fi

# ---------------------------------------------------------------------------
# Codesign — try the named identity, fall back to ad-hoc so `make run`
# always works on a fresh machine without certs.
# ---------------------------------------------------------------------------
sign_args=(--force --sign "$SIGN_IDENTITY")
if [ -f "$ENTITLEMENTS" ]; then
	sign_args+=(--entitlements "$ENTITLEMENTS")
fi

echo "→ codesign ($SIGN_IDENTITY)"
if ! codesign "${sign_args[@]}" "$APP" 2>/dev/null; then
	echo "  identity '$SIGN_IDENTITY' unavailable — falling back to ad-hoc (-)"
	adhoc_args=(--force --sign -)
	if [ -f "$ENTITLEMENTS" ]; then
		adhoc_args+=(--entitlements "$ENTITLEMENTS")
	fi
	codesign "${adhoc_args[@]}" "$APP"
fi

codesign --verify --verbose=1 "$APP"
echo "✓ built $APP"
